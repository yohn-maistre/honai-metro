import assert from 'node:assert/strict'
import { Strata, api, Wiki, chromium, origin, artifactDir } from './environment.mjs'
const s = new Strata(':memory:', origin)
const owner = s.provision('did:web:design-fixture.example', 'Synthetic reader')
const room = s.createCommunity(owner.actor.id, 'Synthetic neighborhood', 'Browser fixture', 'public')
s.createPost(owner.actor.id, room.id, 'Synthetic post: one shared conversation surface.')
const wiki = new Wiki(s), page = wiki.create(owner.actor.id, room.id, 'Synthetic reading reference')
const proposal = wiki.propose(owner.actor.id, page.id, null, 'A synthetic introduction for a reader layout check.\n\n## Everyday knowledge\n\nA comfortable reading surface keeps the context close to the text.\n\n## Sources and perspectives\n\nThis is a browser fixture, not published research.', ['https://example.org/reference'], 'id', 'Synthetic browser fixture')
wiki.decide(owner.actor.id, proposal.id, proposal.digest, true)
const handler = api(s)
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']})
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
  const p = await context.newPage(), errors = []
  p.setDefaultTimeout(15000)
  p.on('pageerror', e => errors.push(e.message))
  // Count actual Web Audio oscillator starts; no stubbed toast/store or success.
  await p.addInitScript(() => {
    window.__chimes = 0
    const start = OscillatorNode.prototype.start
    OscillatorNode.prototype.start = function(...args) { window.__chimes++; return start.apply(this,args) }
  })
  await p.route('**/auth/me',r=>r.fulfill({json:{actor:owner.actor,csrf:'fixture',steward:false}}))
  await p.route('**/v1/**',async r=>{
    const q=r.request(), url=new URL(q.url())
    if(url.pathname==='/v1/news')return r.fulfill({json:{source:{name:'Synthetic news fixture',url:'https://example.org/'},available:true,items:[{id:'1',title:'Synthetic news with a thumbnail',url:'https://example.org/one',publishedAt:'2026-11-11T00:00:00Z',sourceCount:1,image:'/fixture-news.svg'},{id:'2',title:'Synthetic news with an unavailable image',url:'https://example.org/two',publishedAt:null,sourceCount:1,image:'/fixture-unavailable.png'}]}})
    const response=await handler(new Request(q.url(),{method:q.method(),headers:{...q.headers(),authorization:'Bearer '+owner.token,origin},...(q.method()==='POST'?{body:q.postData()}: {})}))
    return r.fulfill({status:response.status,headers:Object.fromEntries(response.headers),body:Buffer.from(await response.arrayBuffer())})
  })
  await p.route('**/fixture-news.svg',r=>r.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"><rect width="80" height="80" fill="#1680fa"/><circle cx="40" cy="40" r="22" fill="#cee6ff"/></svg>'}))
  await p.route('**/fixture-unavailable.png',r=>r.fulfill({status:404,body:''}))
  await p.goto(origin,{waitUntil:'networkidle'})
  await p.getByText('Synthetic post: one shared conversation surface.').waitFor()
  assert.equal(await p.locator('.workspace-picker').count(),0)
  assert.equal(await p.locator('html').getAttribute('data-font-pair'),'jakarta')
  assert.equal(await p.locator('.news-section.compact .news-compact-thumbnail').count(),1)
  assert.equal(await p.locator('.news-section.compact .news-compact-fallback').count(),1)
  const gap=await p.evaluate(()=>document.querySelector('.cx-main').getBoundingClientRect().left-document.querySelector('.etnos-sidebar').getBoundingClientRect().right)
  assert.ok(gap>=16&&gap<=28,'Navigation stays close to the reading column')
  await p.screenshot({path:artifactDir+'/home-desktop.png'})
  await p.goto(origin+'/wiki/'+page.id,{waitUntil:'networkidle'})
  await p.getByRole('heading',{name:'Synthetic reading reference'}).waitFor()
  await p.locator('.wiki-contents summary').click()
  assert.equal(await p.locator('.wiki-contents a').count(),2)
  assert.equal(await p.locator('.wiki-contents .wiki-history-popover').evaluate(el=>{
    const panel=el.getBoundingClientRect(), frame=document.querySelector('.cx-main').getBoundingClientRect()
    return panel.left>=frame.left&&panel.right<=frame.right
  }),true,'Contents stay inside the reader')
  await p.screenshot({path:artifactDir+'/wiki-reader-desktop.png'})
  await p.goto(origin+'/preferences',{waitUntil:'networkidle'})
  await p.getByRole('button',{name:'Coba notifikasi'}).click()
  await p.locator('.tst[data-phase="open"]').waitFor()
  assert.equal(await p.locator('[role="region"][aria-label="Notifikasi"]').count(),1)
  await p.waitForFunction(()=>window.__chimes>0)
  const chimes=await p.evaluate(()=>window.__chimes)
  await p.getByRole('button',{name:'Suara notifikasi',exact:true}).click()
  await p.getByRole('button',{name:'Coba notifikasi'}).click()
  assert.equal(await p.evaluate(()=>window.__chimes),chimes,'Mute suppresses synthesized audio')
  await p.getByLabel('Pasangan huruf',{exact:true}).click()
  await p.getByRole('option',{name:'Geist + Geist Serif',exact:true}).click()
  await p.waitForFunction(()=>document.documentElement.dataset.fontPair==='geist')
  await p.reload({waitUntil:'networkidle'})
  assert.equal(await p.locator('html').getAttribute('data-font-pair'),'geist')
  assert.equal(await p.getByRole('button',{name:'Suara notifikasi',exact:true}).getAttribute('aria-pressed'),'false')
  assert.equal(await p.evaluate(()=>window.__chimes),0,'Reload does not announce old feedback')
  await p.getByRole('button',{name:'Coba notifikasi'}).click()
  await p.locator('.tst[data-phase="open"]').waitFor()
  await p.screenshot({path:artifactDir+'/preferences-toast-desktop.png'})
  await p.keyboard.press('Escape')
  await p.locator('.tst').waitFor({state:'detached'})
  for(const width of [320,390,768,1100,1920]){
    await p.setViewportSize({width,height:844})
    await p.goto(origin,{waitUntil:'networkidle'})
    await p.getByText('Synthetic post: one shared conversation surface.').waitFor()
    assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'No overflow at '+width)
    if(width===390)await p.screenshot({path:artifactDir+'/home-mobile.png'})
  }
  await p.setViewportSize({width:390,height:844})
  await p.goto(origin+'/preferences',{waitUntil:'networkidle'})
  await p.getByRole('button',{name:'Coba notifikasi'}).click()
  await p.locator('.tst[data-phase="open"]').waitFor()
  const bounds=await p.locator('.tst').boundingBox(), dock=await p.locator('.cx-mobile-dock').boundingBox()
  assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390&&bounds.y>=56&&bounds.y+bounds.height<dock.y)
  await p.screenshot({path:artifactDir+'/preferences-toast-mobile.png'})
  await p.getByRole('button',{name:'Terang',exact:true}).click()
  await p.goto(origin,{waitUntil:'networkidle'})
  await p.getByText('Synthetic post: one shared conversation surface.').waitFor()
  await p.screenshot({path:artifactDir+'/home-mobile-light.png'})
  await p.goto(origin+'/wiki/'+page.id,{waitUntil:'networkidle'})
  await p.locator('.wiki-contents summary').click()
  assert.equal(await p.locator('.wiki-contents .wiki-history-popover').evaluate(el=>{
    const panel=el.getBoundingClientRect();return panel.left>=0&&panel.right<=innerWidth
  }),true,'Mobile contents remain within the viewport')
  await p.screenshot({path:artifactDir+'/wiki-reader-mobile-light.png'})
  // Exercise sticky errors through the shared adapter; no deployed write.
  await p.keyboard.press('Escape')
  await p.locator('.tst').waitFor({state:'detached'})
  await p.evaluate(async()=>{const {notifyError}=await import('/src/notifications.svelte.ts');notifyError('Synthetic error: dismissible feedback')})
  await p.getByRole('button',{name:'Tutup notifikasi'}).waitFor()
  assert.equal(await p.locator('.tst').getAttribute('data-type'),'error')
  await p.getByRole('button',{name:'Tutup notifikasi'}).click()
  await p.locator('.tst').waitFor({state:'detached'})
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({realLocalApi:true,geistDefault:true,jakartaPersists:true,actualWebAudio:true,mutePersists:true,noReplay:true,oneDingHost:true,keyboardDismiss:true,imageFallback:true,widths:[320,390,768,1100,1440,1920],errors:0,fixtures:'synthetic only; no production writes'}))
}finally{await browser.close();s.close()}
